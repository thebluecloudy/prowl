#!/usr/bin/env node
/* Worker v197: the hero photos the Prowl page shows (Cockpit's blood moon) are served by the worker like its drawings
   (GET /art/<name>), so they cost the Shopify page nothing. Workers bundle text, not loose files, so this writes the
   WebP files in worker/art/ as base64 into worker/art-photos.js. Run it after changing any of them; a test fails while
   the two differ. Usage: node scripts/build-hero-photos.mjs */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const PHOTO_FILES = { "bloodmoon.webp": "prowl-hero-bloodmoon.webp", "bloodmoon-sm.webp": "prowl-hero-bloodmoon-sm.webp" };
const root = fileURLToPath(new URL("..", import.meta.url));

export function photosSource() {
  const lines = Object.entries(PHOTO_FILES).map(([name, file]) => "  " + JSON.stringify(name) + ": " + JSON.stringify(readFileSync(root + "worker/art/" + file).toString("base64")));
  return "/* Generated by scripts/build-hero-photos.mjs from worker/art/*.webp. Do not edit: change the WebP and rebuild. */\n" +
    "export const PHOTOS_B64 = {\n" + lines.join(",\n") + "\n};\n";
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(root + "worker/art-photos.js", photosSource());
  console.log("worker/art-photos.js: " + Object.keys(PHOTO_FILES).join(", "));
}
