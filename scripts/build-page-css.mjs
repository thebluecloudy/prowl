// Writes worker/page-css.js from page/prowl.html's <style id="prowl-css"> and (page v7.21) worker/page-js.js from its
// <script id="prowl-js">, so the worker serves exactly the stylesheet and main script the deployed page links to. Run
// it after changing the page's CSS or main script: `node scripts/build-page-css.mjs`.
// `--check` only compares, and exits 1 when a worker copy is out of date (npm test does the same).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { pageCss, cssHash, pageJs } from "./page-css.mjs";

const ROOT = new URL("../", import.meta.url);
export const OUT = fileURLToPath(new URL("worker/page-css.js", ROOT));
export const OUT_JS = fileURLToPath(new URL("worker/page-js.js", ROOT));

export function workerModule(html) {
  const css = pageCss(html), hash = cssHash(css);
  return "/* Generated by scripts/build-page-css.mjs from page/prowl.html's <style id=\"prowl-css\">. Do not edit by hand:\n" +
    "   change the page, then run `node scripts/build-page-css.mjs`. The worker serves it at /css/prowl.<hash>.css. */\n" +
    "export const PAGE_CSS_HASH = " + JSON.stringify(hash) + ";\n" +
    "export const PAGE_CSS = " + JSON.stringify(css) + ";\n";
}
/* one line of the script per line of this file, so a change shows as the lines it touched (and two changes to
   different parts of the page merge); the hash line differs every time, so after a merge run the build again */
export function workerJsModule(html) {
  const js = pageJs(html), hash = cssHash(js);
  return "/* Generated by scripts/build-page-css.mjs from page/prowl.html's <script id=\"prowl-js\">. Do not edit by hand:\n" +
    "   change the page, then run `node scripts/build-page-css.mjs`. The worker serves it at /js/prowl.<hash>.js. */\n" +
    "export const PAGE_JS_HASH = " + JSON.stringify(hash) + ";\n" +
    "export const PAGE_JS = [\n" + js.split("\n").map((l) => JSON.stringify(l)).join(",\n") + "\n].join(\"\\n\");\n";
}

if (import.meta.url === "file://" + process.argv[1]) {
  const page = fileURLToPath(new URL("page/prowl.html", ROOT));
  const html = readFileSync(page, "utf8");
  let stale = 0;
  for (const [out, want, name] of [[OUT, workerModule(html), "worker/page-css.js"], [OUT_JS, workerJsModule(html), "worker/page-js.js"]]) {
    let have = "";
    try { have = readFileSync(out, "utf8"); } catch (e) {}
    if (process.argv.includes("--check")) {
      if (have !== want) { console.error(name + " is out of date: run node scripts/build-page-css.mjs"); stale++; }
      else console.log(name + " matches the page");
    } else if (have === want) console.log(name + " already matches the page");
    else { writeFileSync(out, want); console.log("wrote " + name + " (" + Buffer.byteLength(want) + " bytes)"); }
  }
  if (stale) process.exit(1);
}
