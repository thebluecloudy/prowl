// Writes worker/page-css.js from page/prowl.html's <style id="prowl-css">, so the worker serves exactly the stylesheet
// the deployed page links to. Run it after changing the page's CSS: `node scripts/build-page-css.mjs`.
// `--check` only compares, and exits 1 when the worker's copy is out of date (npm test does the same).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { pageCss, cssHash } from "./page-css.mjs";

const ROOT = new URL("../", import.meta.url);
export const OUT = fileURLToPath(new URL("worker/page-css.js", ROOT));

export function workerModule(html) {
  const css = pageCss(html), hash = cssHash(css);
  return "/* Generated by scripts/build-page-css.mjs from page/prowl.html's <style id=\"prowl-css\">. Do not edit by hand:\n" +
    "   change the page, then run `node scripts/build-page-css.mjs`. The worker serves it at /css/prowl.<hash>.css. */\n" +
    "export const PAGE_CSS_HASH = " + JSON.stringify(hash) + ";\n" +
    "export const PAGE_CSS = " + JSON.stringify(css) + ";\n";
}

if (import.meta.url === "file://" + process.argv[1]) {
  const page = fileURLToPath(new URL("page/prowl.html", ROOT));
  const want = workerModule(readFileSync(page, "utf8"));
  let have = "";
  try { have = readFileSync(OUT, "utf8"); } catch (e) {}
  if (process.argv.includes("--check")) {
    if (have !== want) { console.error("worker/page-css.js is out of date: run node scripts/build-page-css.mjs"); process.exit(1); }
    console.log("worker/page-css.js matches the page");
  } else if (have === want) console.log("worker/page-css.js already matches the page");
  else { writeFileSync(OUT, want); console.log("wrote worker/page-css.js (" + Buffer.byteLength(want) + " bytes)"); }
}
