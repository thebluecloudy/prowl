// Writes worker/sw-src.js from worker/sw.js, so the worker can serve the service worker as text (worker v114).
// Run it after changing worker/sw.js: `node scripts/build-sw.mjs`. `--check` only compares and exits 1 when the copy is
// out of date (a test does the same).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = new URL("../", import.meta.url);
export const SRC = fileURLToPath(new URL("worker/sw.js", ROOT));
export const OUT = fileURLToPath(new URL("worker/sw-src.js", ROOT));

export function swModule(src) {
  return "/* Generated by scripts/build-sw.mjs from worker/sw.js. Do not edit by hand: change worker/sw.js, then run\n" +
    "   `node scripts/build-sw.mjs`. The worker serves it at /proxy/sw.js (the shop's /apps/prowl/sw.js). */\n" +
    "export const SW_SRC = " + JSON.stringify(src) + ";\n";
}

if (import.meta.url === "file://" + process.argv[1]) {
  const want = swModule(readFileSync(SRC, "utf8"));
  let have = "";
  try { have = readFileSync(OUT, "utf8"); } catch (e) {}
  if (process.argv.includes("--check")) {
    if (have !== want) { console.error("worker/sw-src.js is out of date: run node scripts/build-sw.mjs"); process.exit(1); }
    console.log("worker/sw-src.js matches worker/sw.js");
  } else if (have === want) console.log("worker/sw-src.js already matches");
  else { writeFileSync(OUT, want); console.log("wrote worker/sw-src.js (" + Buffer.byteLength(want) + " bytes)"); }
}
